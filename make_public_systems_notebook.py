def runtime_zip_bytes() -> bytes:
    """The package as the notebook carries it: code, tests, manifests and generators of this project directory
    (no notebooks, caches, paper pipeline, data). Embedded in the notebook so that nothing has to be uploaded."""
    import io
    import zipfile
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as z:
        for q in sorted(HERE.rglob("*")):
            rel = q.relative_to(HERE)
            if not q.is_file() or "__pycache__" in q.parts or ".pytest_cache" in q.parts or q.suffix in (".pyc", ".ipynb"):
                continue
            if rel.parts[0] in EXCLUDE_TOP:
                continue
            z.write(q, f"cacsa2_project/{rel}")
    return buf.getvalue()


